// Export a Studio project as a plain native Dear ImGui project (GLFW + OpenGL3 host,
// CMake build), and check that the sources compile natively without IMGUI_STUDIO.
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
import { BUILTIN_IMGUI_DIR, RUNTIME_DIR, STUDIO_ROOT, imguiDirFor, loadProjectConfig } from './config.js';
import { makePathMapper, parseDiagnostics } from './diagnostics.js';
import { createZip } from './zip.js';
import { ensureDir, globToRegExp, mapLimit, parseColor, toPosix, walkFiles } from './util.js';
import os from 'node:os';

const SOURCE_EXT = /\.(cpp|cc|cxx|c)$/i;

function slug(s) {
  return String(s || 'imgui-app')
    .replace(/[^a-z0-9]+/gi, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'imgui-app';
}

function cmakeTarget(s) {
  return slug(s).replace(/-/g, '_');
}

function projectSources(projectDir, cfg) {
  const include = cfg.sources.map(globToRegExp);
  const exclude = cfg.exclude.map(globToRegExp);
  return walkFiles(projectDir)
    .filter((f) => SOURCE_EXT.test(f))
    .filter((f) => include.some((re) => re.test(f)))
    .filter((f) => !exclude.some((re) => re.test(f)));
}

const IMGUI_FILES = [
  'imgui.cpp', 'imgui.h', 'imgui_internal.h', 'imgui_draw.cpp', 'imgui_widgets.cpp', 'imgui_tables.cpp', 'imgui_demo.cpp',
  'imconfig.h', 'imstb_rectpack.h', 'imstb_textedit.h', 'imstb_truetype.h', 'LICENSE.txt',
  'backends/imgui_impl_glfw.cpp', 'backends/imgui_impl_glfw.h', 'backends/imgui_impl_opengl3.cpp', 'backends/imgui_impl_opengl3.h',
  'backends/imgui_impl_opengl3_loader.h', 'misc/cpp/imgui_stdlib.cpp', 'misc/cpp/imgui_stdlib.h',
];

function cmakeLists({ target, title, sources, includeDirs, hasAssets, assetDirs }) {
  const src = sources.map((s) => `    ${s}`).join('\n');
  const inc = includeDirs.map((d) => `    \${CMAKE_CURRENT_SOURCE_DIR}/${d}`).join('\n');
  const copies = assetDirs
    .map(
      (d) => `add_custom_command(TARGET ${target} POST_BUILD
    COMMAND \${CMAKE_COMMAND} -E copy_directory \${CMAKE_CURRENT_SOURCE_DIR}/${d} $<TARGET_FILE_DIR:${target}>/${d})`,
    )
    .join('\n');
  return `# Generated by ImGui Studio: native build of "${title}".
#   cmake -S . -B build && cmake --build build
# Uses a system GLFW 3 if available, otherwise downloads it (FetchContent).
cmake_minimum_required(VERSION 3.16)
project(${target} LANGUAGES C CXX)

set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

find_package(OpenGL REQUIRED)
find_package(glfw3 3.3 QUIET)
if(NOT glfw3_FOUND)
  include(FetchContent)
  set(GLFW_BUILD_DOCS OFF CACHE BOOL "" FORCE)
  set(GLFW_BUILD_TESTS OFF CACHE BOOL "" FORCE)
  set(GLFW_BUILD_EXAMPLES OFF CACHE BOOL "" FORCE)
  FetchContent_Declare(glfw GIT_REPOSITORY https://github.com/glfw/glfw.git GIT_TAG 3.4)
  FetchContent_MakeAvailable(glfw)
endif()

set(IMGUI_DIR \${CMAKE_CURRENT_SOURCE_DIR}/imgui)
add_library(imgui STATIC
    \${IMGUI_DIR}/imgui.cpp
    \${IMGUI_DIR}/imgui_draw.cpp
    \${IMGUI_DIR}/imgui_widgets.cpp
    \${IMGUI_DIR}/imgui_tables.cpp
    \${IMGUI_DIR}/imgui_demo.cpp
    \${IMGUI_DIR}/misc/cpp/imgui_stdlib.cpp
    \${IMGUI_DIR}/backends/imgui_impl_glfw.cpp
    \${IMGUI_DIR}/backends/imgui_impl_opengl3.cpp
)
target_include_directories(imgui PUBLIC \${IMGUI_DIR} \${IMGUI_DIR}/backends)
target_link_libraries(imgui PUBLIC glfw OpenGL::GL)

add_executable(${target}
    native/main.cpp
${src}
)
target_include_directories(${target} PRIVATE
    \${CMAKE_CURRENT_SOURCE_DIR}/studio
${inc}
)
target_link_libraries(${target} PRIVATE imgui)
${hasAssets ? `
# Your code loads assets relative to the working directory: copy them next to the executable.
${copies}
set_property(TARGET ${target} PROPERTY VS_DEBUGGER_WORKING_DIRECTORY $<TARGET_FILE_DIR:${target}>)
` : ''}`;
}

function readme({ title, target, sources }) {
  return `# ${title} (exported from ImGui Studio)

This is plain C++ Dear ImGui code. Nothing here depends on ImGui Studio: the
instrumentation macros in \`studio/studio.h\` compile to nothing unless
\`IMGUI_STUDIO\` is defined.

## Build and run the standalone app

\`\`\`sh
cmake -S . -B build
cmake --build build --config Release
cd build && ./${target}      # run from the build dir so assets/ resolves
\`\`\`

Requirements: a C++17 compiler, CMake 3.16+, OpenGL. GLFW is used from your
system when available, otherwise fetched automatically.

## Embed in an existing application

1. Add these sources to your build (plus \`studio/\` and your include dirs):
${sources.map((s) => `   - \`${s}\``).join('\n')}
2. After creating your Dear ImGui context and backends, call \`AppInit()\` once.
3. Every frame, between \`ImGui::NewFrame()\` and \`ImGui::Render()\`, call \`AppFrame()\`.

\`native/main.cpp\` is a complete example of steps 2-3 with GLFW + OpenGL 3.
`;
}

export async function exportProject(studio, { dest = null, zip = true, includeImgui = true } = {}) {
  const projectDir = studio.projectDir;
  const cfg = loadProjectConfig(projectDir);
  const buildId = studio.latestBuildId();
  const name = slug(cfg.name);
  const outDir = dest ? path.resolve(projectDir, dest) : path.join(projectDir, 'export', `${name}${buildId ? `-build${buildId}` : ''}`);
  await fsp.rm(outDir, { recursive: true, force: true });
  await ensureDir(outDir);
  const files = [];
  const add = async (rel, data) => {
    const abs = path.join(outDir, rel);
    await ensureDir(path.dirname(abs));
    await fsp.writeFile(abs, data);
    files.push(rel);
  };

  // Project files (sources, headers, assets); Studio state and exports are skipped by walkFiles.
  const projectImgui = cfg.imgui && cfg.imgui !== 'builtin' ? toPosix(path.relative(projectDir, imguiDirFor(projectDir, cfg))) : null;
  for (const rel of walkFiles(projectDir)) {
    if (rel === 'studio.json' || rel === 'CLAUDE.md' || rel === '.mcp.json') continue;
    if (projectImgui && (rel === projectImgui || rel.startsWith(`${projectImgui}/`))) continue;
    await add(rel, await fsp.readFile(path.join(projectDir, rel)));
  }
  await add('studio/studio.h', await fsp.readFile(path.join(RUNTIME_DIR, 'include', 'studio.h')));
  await add('studio/studio_app.h', await fsp.readFile(path.join(RUNTIME_DIR, 'include', 'studio_app.h')));

  if (includeImgui) {
    const srcImgui = projectImgui ? path.join(projectDir, projectImgui) : BUILTIN_IMGUI_DIR;
    for (const f of IMGUI_FILES) {
      const from = fs.existsSync(path.join(srcImgui, f)) ? path.join(srcImgui, f) : path.join(BUILTIN_IMGUI_DIR, f);
      if (fs.existsSync(from)) await add(`imgui/${f}`, await fsp.readFile(from));
    }
  }

  const clear = parseColor(cfg.background);
  const main = (await fsp.readFile(path.join(RUNTIME_DIR, 'native', 'main.cpp'), 'utf8'))
    .replace('{{TITLE}}', String(cfg.name).replace(/["\\]/g, ''))
    .replace('{{WIDTH}}', String(cfg.viewport.width))
    .replace('{{HEIGHT}}', String(cfg.viewport.height))
    .replace('{{CLEAR_R}}', clear[0].toFixed(4))
    .replace('{{CLEAR_G}}', clear[1].toFixed(4))
    .replace('{{CLEAR_B}}', clear[2].toFixed(4));
  await add('native/main.cpp', main);

  const sources = projectSources(projectDir, cfg);
  const includeDirs = cfg.include_dirs.filter((d) => fs.existsSync(path.join(projectDir, d))).map((d) => toPosix(d).replace(/^\.\/?$/, '.'));
  const assetDirs = cfg.assets.filter((d) => fs.existsSync(path.join(projectDir, d))).map(toPosix);
  const target = cmakeTarget(cfg.name);
  await add('CMakeLists.txt', cmakeLists({ target, title: cfg.name, sources, includeDirs: includeDirs.map((d) => (d === '.' ? '' : d)).map((d) => d || '.'), hasAssets: assetDirs.length > 0, assetDirs }));
  await add('README.md', readme({ title: cfg.name, target, sources }));

  let zipPath = null;
  if (zip) {
    const entries = [];
    for (const rel of files) entries.push({ name: `${path.basename(outDir)}/${rel}`, data: await fsp.readFile(path.join(outDir, rel)) });
    zipPath = `${outDir}.zip`;
    await fsp.writeFile(zipPath, createZip(entries));
  }
  return {
    export_dir: outDir,
    zip: zipPath,
    zip_url: zipPath ? `/project-files/${toPosix(path.relative(projectDir, zipPath))}` : null,
    build_id: buildId,
    files: files.length,
    sources,
    entry_points: 'AppInit() / AppFrame() (see studio/studio_app.h)',
    build_instructions: 'cmake -S . -B build && cmake --build build',
  };
}

function findHostCompiler() {
  for (const c of [process.env.CXX, 'clang++', 'g++', 'c++'].filter(Boolean)) {
    try {
      const v = execFileSync(c, ['--version'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split('\n')[0];
      return { cxx: c, version: v };
    } catch {
      // try next
    }
  }
  return null;
}

function run(cmd, args, opts) {
  return new Promise((resolve) => {
    const child = spawn(cmd, args, { ...opts, stdio: ['ignore', 'pipe', 'pipe'] });
    let out = '';
    child.stdout.on('data', (d) => (out += d));
    child.stderr.on('data', (d) => (out += d));
    child.on('error', (e) => resolve({ code: -1, output: e.message }));
    child.on('close', (code) => resolve({ code, output: out }));
  });
}

// Compile every project source with the host compiler, *without* IMGUI_STUDIO,
// to prove the code does not depend on the Studio runtime.
export async function nativeCheck(studio) {
  const projectDir = studio.projectDir;
  const cfg = loadProjectConfig(projectDir);
  const host = findHostCompiler();
  if (!host) return { ok: null, skipped: true, reason: 'No host C++ compiler found (tried $CXX, clang++, g++, c++)' };
  const imguiDir = imguiDirFor(projectDir, cfg);
  const sources = projectSources(projectDir, cfg);
  const flags = [`-std=${cfg.cxx_std}`, '-fsyntax-only', `-I${imguiDir}`, `-I${path.join(RUNTIME_DIR, 'include')}`];
  for (const inc of cfg.include_dirs) {
    const abs = path.resolve(projectDir, inc);
    if (fs.existsSync(abs)) flags.push(`-I${abs}`);
  }
  for (const d of cfg.defines) flags.push(`-D${d}`);
  if (/clang/.test(host.version)) flags.push('-fno-color-diagnostics');
  else flags.push('-fdiagnostics-color=never');
  const mapPath = makePathMapper({ projectDir, studioRoot: STUDIO_ROOT });
  const results = await mapLimit(sources, Math.max(1, os.cpus().length), async (rel) => {
    const r = await run(host.cxx, [...flags, path.join(projectDir, rel)], { cwd: projectDir });
    return { file: rel, ok: r.code === 0, output: r.output };
  });
  const diags = parseDiagnostics(results.map((r) => r.output).join('\n'), mapPath);
  return {
    ok: results.every((r) => r.ok),
    compiler: host.version,
    checked: sources,
    failed: results.filter((r) => !r.ok).map((r) => r.file),
    errors: diags.filter((d) => d.severity === 'error'),
    warnings: diags.filter((d) => d.severity === 'warning').slice(0, 20),
    note: 'Sources were compiled without IMGUI_STUDIO (studio.h macros disabled), as in a native application.',
  };
}
